<?php
// Run locally:  php backend/database/export_content.php
// Writes backend/database/content.sql: a snapshot of the website CONTENT (text, settings, image names).
// It does NOT include admin users, enquiries or the SMTP settings (those contain private data).
// A new deployment imports this file once, so the live site starts with the same content as your local site.
if (PHP_SAPI !== 'cli') { http_response_code(403); exit('CLI only'); }
require __DIR__ . '/../includes/bootstrap.php';

const TABLES = [
    'brand', 'seo', 'header_settings', 'website_menu', 'hero_settings',
    'ip_services_section', 'ip_services', 'growth_section', 'growth_cards',
    'how_section', 'how_steps', 'cta_banner', 'approach',
    'faq_section', 'faq_items', 'contact_section', 'footer_settings',
    'legal_pages', 'floating_icons',
];

$pdo = db();
$out = "-- JBM content snapshot (generated by export_content.php)\n-- @@\n";
foreach (TABLES as $t) {
    $rows = $pdo->query("SELECT * FROM `$t`")->fetchAll(PDO::FETCH_ASSOC);
    $out .= "DELETE FROM `$t`\n-- @@\n";
    foreach ($rows as $r) {
        $cols = implode(', ', array_map(fn($c) => "`$c`", array_keys($r)));
        $vals = implode(', ', array_map(fn($v) => $v === null ? 'NULL' : $pdo->quote((string)$v), $r));
        $out .= "REPLACE INTO `$t` ($cols) VALUES ($vals)\n-- @@\n";
    }
    echo str_pad($t, 22), count($rows), " rows\n";
}
file_put_contents(__DIR__ . '/content.sql', $out);
echo "Wrote backend/database/content.sql (" . strlen($out) . " bytes)\n";
