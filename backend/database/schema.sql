CREATE DATABASE IF NOT EXISTS jbm CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE jbm;

CREATE TABLE IF NOT EXISTS admins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(60) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(100) NOT NULL DEFAULT '',
  email VARCHAR(150) NOT NULL DEFAULT '',
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  is_superuser TINYINT(1) NOT NULL DEFAULT 0,
  last_login DATETIME NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS brand (
  id TINYINT UNSIGNED PRIMARY KEY,
  website_name VARCHAR(120) NOT NULL DEFAULT '',
  header_logo VARCHAR(255) NOT NULL DEFAULT '',
  footer_logo VARCHAR(255) NOT NULL DEFAULT '',
  favicon VARCHAR(255) NOT NULL DEFAULT '',
  show_credits TINYINT(1) NOT NULL DEFAULT 1,
  credits_url VARCHAR(255) NOT NULL DEFAULT '',
  company_name VARCHAR(100) NOT NULL DEFAULT '',
  company_descriptor VARCHAR(120) NOT NULL DEFAULT '',
  tagline VARCHAR(120) NOT NULL DEFAULT '',
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS seo (
  id TINYINT UNSIGNED PRIMARY KEY,
  meta_title VARCHAR(255) NOT NULL DEFAULT '',
  meta_description VARCHAR(500) NOT NULL DEFAULT '',
  primary_keywords TEXT NULL,
  secondary_keywords TEXT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS email_settings (
  id TINYINT UNSIGNED PRIMARY KEY,
  smtp_host VARCHAR(190) NOT NULL DEFAULT '',
  smtp_port SMALLINT UNSIGNED NOT NULL DEFAULT 587,
  encryption ENUM('none','ssl','tls') NOT NULL DEFAULT 'tls',
  smtp_username VARCHAR(190) NOT NULL DEFAULT '',
  smtp_password TEXT NULL,
  from_email VARCHAR(190) NOT NULL DEFAULT '',
  from_name VARCHAR(120) NOT NULL DEFAULT '',
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS website_menu (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
